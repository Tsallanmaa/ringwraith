# ---------------------------------------------------------------- dates
def _month_index(name: str) -> int:
    key = name.strip().lower()
    for i, (n, short, _, _) in enumerate(MONTHS):
        if key in (n.lower(), short.lower()):
            return i
    for i, (n, _, _, _) in enumerate(MONTHS):
        if n.lower().startswith(key):
            return i
    raise ObsidianError(f"unknown Shire month: {name}")


def parse_date(text: str) -> dict:
    """'1 Astron 2965', 'Astron 1 2965' or '2965-Astron-1' -> {year, month (0-based), day}."""
    t = text.strip()
    m = re.fullmatch(r"(\d{3,4})-([^-]+)-(\d{1,2})", t)
    if m:
        year, month, day = int(m.group(1)), m.group(2), int(m.group(3))
    else:
        nums = [int(x) for x in re.findall(r"\b\d+\b", t)]
        words = re.sub(r"\b\d+\b", " ", t).strip(" ,")
        if len(nums) != 2 or not words:
            raise ObsidianError(f"can't read the date {text!r}; write it like '1 Astron 2965'")
        day, year = (nums[0], nums[1]) if nums[0] < nums[1] else (nums[1], nums[0])
        month = words
    mi = _month_index(month)
    if not 1 <= day <= MONTHS[mi][2]:
        raise ObsidianError(f"{MONTHS[mi][0]} has {MONTHS[mi][2]} day(s)")
    return {"year": year, "month": mi, "day": day}


def day1(settings: dict | None = None) -> dict:
    settings = settings or cp.load_settings()
    return parse_date(str((settings.get("calendar") or {}).get("day1") or "1 Astron 2965"))


def tale_date(tale_day: int, settings: dict | None = None) -> dict:
    """The calendar date of a tale day (day 1 = the campaign's `calendar.day1`)."""
    start = day1(settings)
    ordinal = sum(MONTHS[i][2] for i in range(start["month"])) + start["day"] - 1 + (int(tale_day) - 1)
    year = start["year"] + ordinal // YEAR_DAYS
    ordinal %= YEAR_DAYS
    for i, (_, _, length, _) in enumerate(MONTHS):
        if ordinal < length:
            return {"year": year, "month": i, "day": ordinal + 1}
        ordinal -= length
    raise AssertionError("unreachable")


def show(date: dict) -> str:
    name, _, length, _ = MONTHS[date["month"]]
    return f"{name}, {date['year']}" if length == 1 else f"{date['day']} {name} {date['year']}"


def fc_date(date: dict) -> str:
    """Calendarium's note date format, YYYY-MM-DD with 1-based months."""
    return f"{date['year']}-{date['month'] + 1}-{date['day']}"


