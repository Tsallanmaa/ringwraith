def _lore_atom(slug: str) -> Path:
    from . import config as cfg
    f = cfg.REPO_ROOT / "lore" / "atoms" / "adversaries" / f"{slug.removesuffix('.md')}.md"
    if not f.exists():
        raise ObsidianError(f"no adversary atom lore/atoms/adversaries/{slug}.md")
    return f


def statblock_yaml(slug: str, name: str | None = None) -> str:
    """The lore atom's stat block as a Fantasy Statblocks code block in the One Ring layout."""
    text = _lore_atom(slug).read_text(encoding="utf-8")
    m = re.search(r"```statblock\n(.*?)```", text, re.S)
    if not m:
        raise ObsidianError(f"{slug} has no stat block")
    sb = yaml.safe_load(m.group(1)) or {}
    parry = sb.get("parry")
    hate = sb.get("hate") if sb.get("hate") not in (None, 0) or sb.get("resolve") in (None, 0) else None
    hate_or_resolve = f"{sb['resolve']} Resolve" if hate is None and sb.get("resolve") else (sb.get("hate") or 0)

    def prof(p: dict) -> dict:
        special = ", ".join(str(s).title() for s in p.get("special") or [])
        bits = [f"Damage {p.get('damage')}", f"Injury {p.get('injury')}"] + ([special] if special else [])
        return {"name": f"{p.get('name')} {p.get('rating')}", "desc": " · ".join(bits)}

    out = {
        "layout": LAYOUT_NAME,
        "name": name or sb.get("name") or slug,
        "features": ", ".join(sb.get("distinctive_features") or []) or None,
        "tor_stats": [sb.get("attribute_level"), sb.get("endurance"), sb.get("might"), hate_or_resolve,
                      f"+{parry}" if isinstance(parry, int) and parry > 0 else "–", sb.get("armour")],
        "proficiencies": [prof(p) for p in sb.get("proficiencies") or []],
        "fell_abilities": [{"name": a.get("name"), "desc": a.get("text", "")} for a in sb.get("fell_abilities") or []],
    }
    out = {k: v for k, v in out.items() if v not in (None, [], "")}
    stats = out.pop("tor_stats")       # one readable row: [AL, Endurance, Might, Hate, Parry, Armour]
    text = yaml.safe_dump(out, sort_keys=False, allow_unicode=True, width=1000)
    row = yaml.safe_dump(stats, default_flow_style=True, allow_unicode=True, width=1000).strip()
    head, sep, rest = text.partition("proficiencies:")
    text = f"{head}tor_stats: {row}\n{sep}{rest}" if sep else f"{text}tor_stats: {row}\n"
    return "```statblock\n" + text + "```\n"


@fileio.with_lock      # the art worker writes the portrait into the same note
def statblock(note: str, slug: str) -> Path:
    """Put (or replace) the stat block section in an adversary's vault note."""
    path = vault.resolve_note(note)
    fm, body = vault.read_note(path)
    block = f"{STATBLOCK_SECTION}\n" + statblock_yaml(slug, fm.get("name"))   # the source is kept in statblock_from
    if STATBLOCK_SECTION in body:
        body = re.sub(rf"{re.escape(STATBLOCK_SECTION)}\n.*?(?=\n## |\Z)", block.rstrip("\n") + "\n", body,
                      count=1, flags=re.S)
    else:
        body = body.rstrip("\n") + "\n\n" + block
    fm["statblock_from"] = slug
    vault.write_note(path, fm, body)
    return path


