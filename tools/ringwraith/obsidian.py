"""Obsidian extras for a campaign vault: the Shire Reckoning calendar (Calendarium), stat blocks
(Fantasy Statblocks) and the Home dashboard.

- `setup()` writes the plugins' settings into the vault (`.obsidian/plugins/<id>/data.json`), merging with
  whatever is there: the Shire Reckoning calendar for Calendarium and "The One Ring" layout for Fantasy
  Statblocks. Close Obsidian (or reload the plugins) first. The layout is also saved as a JSON file that can
  be imported by hand (Fantasy Statblocks settings → Layouts → Import From JSON).
- Tale days map onto the calendar from the campaign setting `calendar.day1` (default 1 Astron 2965).
- `sync()` gives session, journey and mission notes Calendarium event frontmatter (`fc-*`) from their tale
  days, and moves the calendar's "today" to the tale's day.
- `statblock()` copies an adversary's stat block from the lore library into its vault note, as a
  `statblock` code block in the One Ring layout. Only for foes the hero has fought or studied.
- `home()` rewrites the generated part of `00 Home.md` as a logbook of the tale: where it stands, the latest
  days, the last chapter, what lies ahead, the threads, the company and the road.

The calendar follows the Shire Reckoning of The Lord of the Rings, Appendix D: twelve months of thirty days,
the two Yule days at the turn of the year and the Lithe days at midsummer. Years are Third Age years (the
Shire's own count is 1600 less). Overlithe (the leap day) is left out.
"""

