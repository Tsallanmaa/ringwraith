def _link(path_or_rel: str | Path, vault_dir: Path, size: int | None = None) -> str:
    rel = Path(path_or_rel)
    rel = rel.relative_to(vault_dir) if rel.is_absolute() else rel
    return f"![[{rel.as_posix()}{'|' + str(size) if size else ''}]]"


def _image(fm: dict) -> str | None:
    img = str(fm.get("image") or "").strip().removeprefix("[[").removesuffix("]]")
    return img or None


def _last_scene(vault_dir: Path) -> str | None:
    done = cp.private_dir() / "art-done.jsonl"
    if not done.exists():
        return None
    for line in reversed(done.read_text(encoding="utf-8").splitlines()):
        try:
            job = json.loads(line)
        except ValueError:
            continue
        if job.get("status") == "done" and job.get("preset") == "scene" and (vault_dir / job["file"]).exists():
            return job["file"]
    return None


def _map_image(location: str, vault_dir: Path) -> str | None:
    try:
        from . import geo
        _, map_id, _ = geo.find(re.sub(r"\[\[|\]\]", "", location or ""))
    except Exception:  # noqa: BLE001 - no map yet is fine
        return None
    f = vault_dir / "90 Assets" / "maps" / f"{map_id}.jpg"
    return f"90 Assets/maps/{map_id}.jpg" if f.exists() else None


def _road_image(vault_dir: Path) -> tuple[str, str] | None:
    """The session road map of the latest real journey (its route drawn, the company's place marked),
    with a caption: ('90 Assets/maps/session-003-eriador.jpg', 'Session 3: Archet to The Old Watch')."""
    try:
        from . import geo
        legs = geo.legs()
    except Exception:  # noqa: BLE001 - no travel log yet is fine
        return None
    road = [l for l in legs if l.get("session") and geo.is_notable(l)]
    heroes_dir = vault_dir / vault.NOTE_TYPES["hero"]
    heroes = {p.stem for p in heroes_dir.glob("*.md")} if heroes_dir.is_dir() else set()
    with_hero = [l for l in road if heroes & set(l.get("who") or [])]
    for leg in reversed(with_hero or road):     # the hero's own road, not an errand someone else ran
        rel = f"90 Assets/maps/session-{int(leg['session']):03d}-{leg['map']}.jpg"
        if (vault_dir / rel).exists():
            return rel, f"Session {leg['session']}, day {leg['day']}: {leg['from']} to {leg['to']}"
        return None                              # not drawn yet: the plain map will do
    return None


def _plain_link(text: str) -> str:
    return re.sub(r"\[\[([^\]|]+)(?:\|([^\]]+))?\]\]", lambda m: m.group(2) or m.group(1), text or "")


def _sentences(text: str, n: int) -> str:
    parts = re.split(r"(?:(?<=[.!?…])|(?<=[.!?…][\"”’]))\s+", text.strip())
    if len(text) <= 600 or len(parts) <= n:
        out = text.strip()
    else:
        out = " ".join(parts[:n]).rstrip("*_") + " …"
    if out.count("*") % 2:                     # a cut inside *italics*: close them
        out = out.rstrip(" …") + "* …"
    return out


def _last_chapter(note: Path) -> dict:
    """Title, painting and the closing lines of a session note's tale."""
    fm, body = vault.read_note(note)
    m = re.search(r"^# (.+)$", body, re.M)
    title = m.group(1).strip() if m else note.stem
    tale = re.search(r"^## The tale\s*\n(.*?)(?=^## |\Z)", body, re.S | re.M)
    paras = [p.strip() for p in (tale.group(1) if tale else "").split("\n\n")]
    paras = [p for p in paras if p and not p.startswith(("![[", ">", "#", "|", "- "))]
    return {"title": title, "image": _image(fm), "ending": _sentences(paras[-1], 3) if paras else "",
            "when": fm.get("in_game_date")}


NUMBER_WORDS = ["no", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine", "ten", "eleven",
                "twelve", "thirteen", "fourteen", "fifteen", "sixteen", "seventeen", "eighteen", "nineteen", "twenty"]


def _hence(left: int) -> str:
    """How far off a day is, the way a chronicler would say it."""
    if left == 0:
        return "this very day"
    if left == 1:
        return "on the morrow"
    if left < 0:
        return f"{_count(-left)} day{'s' if left < -1 else ''} past"
    return f"{_count(left)} days hence"


def _count(n: int) -> str:
    return NUMBER_WORDS[n] if 0 <= n < len(NUMBER_WORDS) else str(n)


def home_markdown(vault_dir: Path | None = None) -> str:
    """The Home page as a logbook of the tale: where it stands, the latest days, the last chapter, what lies
    ahead, the threads, the company and the road. Short, in the tale's voice; numbers kept small and low."""
    vault_dir = vault_dir or cp.campaign_dir()
    st = _state()
    settings = cp.load_settings()
    day = int(st.get("day") or 1)
    lines = [HOME_START, ""]

    def on(d: int) -> str:              # "11 Astron" (the year is in the heading)
        try:
            text = show(tale_date(d, settings))
        except ObsidianError:
            return f"day {d}"
        return text.rsplit(" ", 1)[0].rstrip(",")

    # ---- where the tale stands
    try:
        today = show(tale_date(day, settings))
    except ObsidianError:
        today = str(st.get("date") or "")
    when = str(st.get("time") or "").strip()
    head = f"{when[:1].upper() + when[1:] + ', ' if when else ''}{today}"
    place = _plain_link(str(st.get("location") or ""))
    moment = _plain_link(str(st.get("scene") or "")).strip()
    moment = re.sub(r"^(?:[\w-]+ ){0,2}of day \d+,\s*", "", moment, flags=re.I)   # the heading already says when
    img = _last_scene(vault_dir)
    lines.append(f"> [!tale] {head}{' · ' + place if place else ''}")
    if img:
        lines += [f"> {_link(img, vault_dir, 720)}", ">"]
    lines += [f"> *{moment[:1].upper() + moment[1:] if moment else 'The tale waits to be told.'}*", ""]

    # ---- from the logbook: the last three days with entries, a line each
    events = [e for e in calendar_events(vault_dir) if e["kind"] == "Event" and e["day"] <= day]
    days = sorted({e["day"] for e in events})[-3:]
    if days:
        lines += ["## From the logbook"]
        for d in reversed(days):
            text = " ".join(_sentences(e["text"], 2) for e in events if e["day"] == d)
            lines.append(f"- **{on(d)}.** {text}")
        lines += ["", "*[[10 Campaign/Calendar|The tale day by day]] · [[10 Campaign/Timeline|Timeline]]*", ""]

    # ---- the last chapter
    sessions = sorted((vault_dir / vault.NOTE_TYPES["session"]).glob("*.md"))
    if sessions:
        ch = _last_chapter(sessions[-1])
        title = re.sub(r"^Session \d+:\s*", "", ch["title"])
        lines += [f"## The last chapter: [[{sessions[-1].stem}|{title}]]"]
        if ch["image"]:
            lines.append(f"![[{ch['image']}|420]]")
        if ch["ending"]:
            lines += [f"> {ch['ending']}"]
        lines += ["", "*[[10 Campaign/Sessions|All chapters]]*", ""]

    # ---- what lies ahead: one line per day
    deadlines = sorted((d for d in st.get("deadlines") or [] if d.get("due") is not None), key=lambda d: d["due"])
    if deadlines or st.get("counters"):
        lines.append("## What lies ahead")
        for due in sorted({int(d["due"]) for d in deadlines}):
            names = " · ".join(str(d.get("name")) for d in deadlines if int(d["due"]) == due)
            lines.append(f"- **{on(due)}**, {_hence(due - day)}: {names}")
        for c in st.get("counters") or []:
            lines.append(f"- {c.get('name')}: the {_ordinal(day - int(c.get('since', day)) + 1)} day")
        lines.append("")

    # ---- threads in hand: one compact run
    try:
        from .tale import threads
        open_threads = threads()["open"]
    except Exception:  # noqa: BLE001
        open_threads = []
    if open_threads:
        names = [re.sub(r"\s*\((?:day|days)[^)]*\)", "", t["title"]).strip() for t in open_threads]
        lines += ["## Threads in hand", " ◇ ".join(names), "",
                  "*[[10 Campaign/Threads|The threads in full]] · [[10 Campaign/Compass|Compass]]*", ""]

    # ---- the company: one strip of portraits
    heroes = sorted((vault_dir / vault.NOTE_TYPES["hero"]).glob("*.md"))[:1]
    allies = sorted((vault_dir / vault.NOTE_TYPES["ally"]).glob("*.md"))
    if heroes or allies:
        band = vault_dir / "20 Fellowship" / "Band.md"
        bfm, bbody = vault.read_note(band) if band.exists() else ({}, "")
        m = re.search(r"^# (?:The Band:\s*)?(.+)$", bbody, re.M)       # "# The Band: the Order of …"
        title = m.group(1).strip() if m and m.group(1).strip().lower() != "the band" else ""
        company = bfm.get("name") or (title[:1].upper() + title[1:] if title else "The company")
        pics, names, marks = [], [], []
        stats = ""
        for f in heroes + allies:
            fm = vault.read_note(f)[0]
            img = _image(fm)
            pics.append(f"![[{img}\\|{72 if f in heroes else 56}]]" if img else "")   # \| : a pipe inside a table
            first = f.stem.split()[0]
            names.append(f"**[[{f.stem}\\|{first}]]**{' ★' if fm.get('hardened') else ''}")
            trouble = [str(fm[k]) for k in ("injury", "fatigue") if fm.get(k) and str(fm[k]).lower() not in ("none", "0")]
            if fm.get("status") not in (None, "", "active"):
                trouble.append(str(fm["status"]))
            trouble += [k for k, v in (fm.get("conditions") or {}).items() if v]
            marks.append(f"*{', '.join(trouble)}*" if trouble else "")
            if f in heroes:
                end, hope, sh = fm.get("endurance") or {}, fm.get("hope") or {}, fm.get("shadow") or {}
                stats = (f"{first}: Endurance {end.get('current', '–')}/{end.get('max', '–')} · Hope "
                         f"{hope.get('current', '–')}/{hope.get('max', '–')} · Shadow {sh.get('points', 0)}")
        if bfm.get("readiness"):
            stats += f"{' · ' if stats else ''}Readiness {bfm['readiness']}"
        lines += [f"## {company}", "| " + " | ".join(pics) + " |", "|" + ":-:|" * len(pics),
                  "| " + " | ".join(names) + " |"]
        if any(marks):
            lines.append("| " + " | ".join(marks) + " |")
        if stats:
            lines += ["", f"<small>{stats}</small>"]
        lines.append("")

    # ---- the road
    road = _road_image(vault_dir)
    mp = road[0] if road else _map_image(str(st.get("location") or ""), vault_dir)
    if mp:
        lines += ["## The road", _link(mp, vault_dir, 640), *([f"*{road[1]}*"] if road else []), "",
                  "*[[60 Maps/Maps|All maps]] · [[60 Maps/Travel log|Travel log]]*", ""]
    lines.append(HOME_END)
    return "\n".join(lines)


def _ordinal(n: int) -> str:
    return f"{n}{'th' if 10 <= n % 100 <= 20 else {1: 'st', 2: 'nd', 3: 'rd'}.get(n % 10, 'th')}"


@fileio.with_lock
def home(vault_dir: Path | None = None) -> Path:
    """Rewrite the generated block of 00 Home.md (above the links), keeping everything else."""
    vault_dir = vault_dir or cp.campaign_dir()
    f = vault_dir / "00 Home.md"
    fm, body = vault.read_note(f) if f.exists() else ({}, "")
    calendar_note(vault_dir)
    block = home_markdown(vault_dir)
    if HOME_START in body and HOME_END in body:
        body = body[:body.index(HOME_START)] + block + body[body.index(HOME_END) + len(HOME_END):]
    else:
        m = re.search(r"^# .*\n(?:\n\*.*\*\n)?", body, re.M)     # after the title and its subtitle
        at = m.end() if m else 0
        body = body[:at] + "\n" + block + "\n\n" + body[at:].lstrip("\n")
    vault.write_note(f, fm, body)
    return f
