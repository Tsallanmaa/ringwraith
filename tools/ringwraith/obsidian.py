def _plugin_dir(plugin: str, vault_dir: Path | None = None) -> Path:
    return (vault_dir or cp.campaign_dir()) / ".obsidian" / "plugins" / plugin


def _read_json(path: Path) -> dict:
    try:
        return json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}
    except ValueError as e:
        raise ObsidianError(f"{path} is not valid JSON ({e}); fix or delete it first") from e


def _write_json(path: Path, data: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fileio.atomic_write(path, json.dumps(data, indent=2, ensure_ascii=False))


THEME_SRC = Path(__file__).resolve().parents[2] / "vault-kit" / "obsidian" / "ringwraith.css"
THEME_NAME = "ringwraith"


def install_theme(vault_dir: Path | None = None) -> Path:
    """Copy the Parchment/Shadow snippet into the vault and switch it on (appearance.json)."""
    vault_dir = vault_dir or cp.campaign_dir()
    dest = vault_dir / ".obsidian" / "snippets" / f"{THEME_NAME}.css"
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(THEME_SRC.read_text(encoding="utf-8"), encoding="utf-8")
    f = vault_dir / ".obsidian" / "appearance.json"
    data = _read_json(f)
    snippets = data.get("enabledCssSnippets") or []
    if THEME_NAME not in snippets:
        data["enabledCssSnippets"] = snippets + [THEME_NAME]
        _write_json(f, data)
    return dest


def setup(vault_dir: Path | None = None) -> list[str]:
    """Write the calendar and the layout into the plugins' settings, keeping everything else there."""
    vault_dir = vault_dir or cp.campaign_dir()
    done = []
    f = _plugin_dir(CALENDARIUM, vault_dir) / "data.json"
    data = _read_json(f)
    cals = [c for c in data.get("calendars", []) if c.get("id") != CALENDAR_ID and c.get("name") != CALENDAR_NAME]
    old = next((c for c in data.get("calendars", []) if c.get("id") == CALENDAR_ID), None)
    cal = calendar(_today_date())
    if old:      # keep events and categories the player added in Obsidian
        cal["events"] = old.get("events", [])
        cal["categories"] = old.get("categories") or cal["categories"]
    data["calendars"] = [cal] + cals
    data.setdefault("defaultCalendar", CALENDAR_ID)
    if not data.get("defaultCalendar"):
        data["defaultCalendar"] = CALENDAR_ID
    data["autoParse"] = True             # read fc-* frontmatter from notes
    _write_json(f, data)
    done.append(f"Calendarium: '{CALENDAR_NAME}' calendar in {f.relative_to(vault_dir)}")

    f = _plugin_dir(STATBLOCKS, vault_dir) / "data.json"
    data = _read_json(f)
    lay = layout()
    data["layouts"] = [x for x in data.get("layouts", []) if x.get("name") != LAYOUT_NAME] + [lay]
    _write_json(f, data)
    done.append(f"Fantasy Statblocks: '{LAYOUT_NAME}' layout in {f.relative_to(vault_dir)}")

    done.append(f"theme: {install_theme(vault_dir).relative_to(vault_dir)} (Parchment in light mode, Shadow in dark)")
    written = vault.write_indexes(vault_dir)
    if written:
        done.append(f"index notes as Bases: {', '.join(f.stem for f in written)}")

    copy = vault_dir / "90 Assets" / "obsidian" / "the-one-ring.statblock-layout.json"
    _write_json(copy, lay)
    done.append(f"layout also saved for import by hand: {copy.relative_to(vault_dir)}")
    return done


# ---------------------------------------------------------------- events from notes
def _state() -> dict:
    from . import clock
    try:
        return clock.state()[1]
    except (cp.CampaignError, OSError):
        return {}


def _today_date() -> dict | None:
    try:
        return tale_date(int(_state().get("day") or 1))
    except (ObsidianError, TypeError, ValueError):
        return None


def _days(value: Any) -> tuple[int, int] | None:
    """'5-11', '5–11', [5, 11] or 7 -> (first, last)."""
    if value in (None, "", []):
        return None
    if isinstance(value, (list, tuple)):
        nums = [int(v) for v in value]
    else:
        nums = [int(x) for x in re.findall(r"\d+", str(value))]
    return (min(nums), max(nums)) if nums else None


def note_title(f: Path, fm: dict, body: str) -> str:
    """A note's own title: its first heading ("Session 2: The Fog at the Grey Stone"), else its name."""
    m = re.search(r"^# (.+)$", body, re.M)
    if m and m.group(1).strip() not in ("{{name}}", f.stem):
        return m.group(1).strip()
    if fm.get("name"):
        return str(fm["name"])
    return f"Session {fm['session']}" if fm.get("session") else f.stem


@fileio.with_lock
def sync(vault_dir: Path | None = None) -> list[str]:
    """Calendarium frontmatter on session, journey and mission notes; the calendar's today."""
    vault_dir = vault_dir or cp.campaign_dir()
    settings = cp.load_settings()
    changed = []
    sources = [("session", "Session", "tale_days", None), ("journey", "Journey", "start_day", "end_day"),
               ("mission", "Mission", "start_day", "end_day")]
    for kind, category, first_key, last_key in sources:
        folder = vault_dir / vault.NOTE_TYPES[kind]
        for f in sorted(folder.glob("*.md")) if folder.is_dir() else []:
            fm, body = vault.read_note(f)
            span = _days(fm.get(first_key))
            if span and last_key and fm.get(last_key):
                span = (span[0], _days(fm.get(last_key))[1])
            if not span:
                continue
            start, end = tale_date(span[0], settings), tale_date(span[1], settings)
            want = {"fc-calendar": CALENDAR_NAME, "fc-date": fc_date(start), "fc-category": category,
                    "fc-display-name": note_title(f, fm, body)}
            if span[1] != span[0]:
                want["fc-end"] = fc_date(end)
            if any(fm.get(k) != v for k, v in want.items()) or ("fc-end" in fm and "fc-end" not in want):
                fm.pop("fc-end", None)
                fm.update(want)
                vault.write_note(f, fm, body)
                changed.append(f"{f.relative_to(vault_dir)}: {show(start)}" + (f" to {show(end)}" if span[1] != span[0] else ""))
    f = _plugin_dir(CALENDARIUM, vault_dir) / "data.json"
    today = _today_date()
    if f.exists() and today:
        data = _read_json(f)
        for c in data.get("calendars", []):
            if c.get("id") == CALENDAR_ID and c.get("current") != today:
                c["current"] = today
                _write_json(f, data)
                changed.append(f"calendar today: {show(today)}")
    return changed


# ---------------------------------------------------------------- the Calendar note (a readable list)
CALENDAR_NOTE = "10 Campaign/Calendar.md"
_DAYS_RX = re.compile(r"\bdays?\s+(\d+)(?:\s*[–-]\s*(\d+))?|\b(\d+)(?:st|nd|rd|th)\s+day\b", re.I)


def _timeline_days(cell: str) -> tuple[int, int] | None:
    """'2965, spring (day 6)' -> (6, 6); '(days 8–10)' -> (8, 10); '(5th day)' -> (5, 5). Counts like
    'Herb 4 days overdue' are not tale days and are skipped."""
    if re.search(r"\d+\s+days?\s+(overdue|late|ago|off)", cell, re.I):
        return None
    m = _DAYS_RX.search(cell)
    if not m:
        return None
    if m.group(3):
        n = int(m.group(3))
        return n, n
    a = int(m.group(1))
    return a, int(m.group(2) or a)


def calendar_events(vault_dir: Path | None = None) -> list[dict]:
    """Everything the tale has dated, as {day, end, kind, text}."""
    vault_dir = vault_dir or cp.campaign_dir()
    events: list[dict] = []
    for kind, first_key, last_key, label in (("session", "tale_days", None, "Session"),
                                            ("journey", "start_day", "end_day", "Journey"),
                                            ("mission", "start_day", "end_day", "Mission")):
        folder = vault_dir / vault.NOTE_TYPES[kind]
        for f in sorted(folder.glob("*.md")) if folder.is_dir() else []:
            fm, body = vault.read_note(f)
            span = _days(fm.get(first_key))
            if span and last_key and fm.get(last_key):
                span = (span[0], _days(fm.get(last_key))[1])
            if span:
                title = note_title(f, fm, body)
                text = f"[[{f.stem}|{title}]]" if title != f.stem else f"[[{f.stem}]]"
                events.append({"day": span[0], "end": span[1], "kind": label, "text": text})
    travels = cp.private_dir() / "travels.jsonl"
    if travels.exists():
        for line in travels.read_text(encoding="utf-8").splitlines():
            try:
                leg = json.loads(line)
            except ValueError:
                continue
            if not leg.get("day"):
                continue
            who = leg.get("who") or []
            who = ", ".join(who[:3]) + (f" and {len(who) - 3} more" if len(who) > 3 else "")
            how = f", {leg['mode']}" if leg.get("mode") else ""
            when = f"{leg['time']}: " if leg.get("time") else ""
            events.append({"day": int(leg["day"]), "end": int(leg["day"]), "kind": "Road",
                           "text": f"{when}{who}: {leg.get('from')} → {leg.get('to')}{how}"})
    timeline = vault_dir / "10 Campaign" / "Timeline.md"
    if timeline.exists():
        for row in vault.read_note(timeline)[1].splitlines():
            cells = [c.strip() for c in row.strip().strip("|").split("|")]
            if len(cells) >= 2 and (span := _timeline_days(cells[0])):
                events.append({"day": span[0], "end": span[1], "kind": "Event", "text": cells[1]})
    for d in _state().get("deadlines") or []:
        if d.get("due"):
            note = f" ({d['note']})" if d.get("note") else ""
            events.append({"day": int(d["due"]), "end": int(d["due"]), "kind": "Deadline",
                           "text": f"**{d.get('name')}**{note}"})
    order = {"Session": 0, "Mission": 1, "Journey": 2, "Event": 3, "Road": 4, "Deadline": 5}
    return sorted(events, key=lambda e: (e["day"], order.get(e["kind"], 9)))


def calendar_note(vault_dir: Path | None = None) -> Path:
    """Write `10 Campaign/Calendar.md`: the tale day by day, with Shire dates, grouped by month."""
    vault_dir = vault_dir or cp.campaign_dir()
    settings = cp.load_settings()
    today = int(_state().get("day") or 1)
    icons = {"Session": "📜", "Mission": "⚑", "Journey": "🧭", "Event": "✦", "Road": "👣", "Deadline": "⧗"}
    lines = ["# Calendar of the tale", "",
             f"*Shire Reckoning, in Third Age years. Tale day 1 is {show(day1(settings))}. Written by Ringwraith "
             f"(`ringwraith obsidian home`); changes here are overwritten. The calendar view: `{CALENDAR_NAME}` "
             "in Calendarium.*", ""]
    events = calendar_events(vault_dir)
    days = sorted({e["day"] for e in events} | {today})
    month = None
    for d in days:
        date = tale_date(d, settings)
        name, _, length, _ = MONTHS[date["month"]]
        head = f"{name} {date['year']}" if length > 1 else f"{name}, {date['year']}"
        if head != month:
            lines += ["", f"## {head}", ""]
            month = head
        mark = " ◀ **today**" if d == today else ""
        lines.append(f"- **{show(date).rsplit(' ', 1)[0] if length > 1 else name}** · day {d}{mark}")
        for e in (x for x in events if x["day"] == d):
            span = f" (to {show(tale_date(e['end'], settings))}, day {e['end']})" if e["end"] != e["day"] else ""
            future = " *(to come)*" if e["kind"] == "Deadline" and d > today else ""
            lines.append(f"    - {icons.get(e['kind'], '•')} {e['text']}{span}{future}")
    f = vault_dir / CALENDAR_NOTE
    f.parent.mkdir(parents=True, exist_ok=True)
    fm = {"type": "calendar"}
    vault.write_note(f, fm, "\n".join(lines).replace("\n\n\n", "\n\n") + "\n")
    return f


